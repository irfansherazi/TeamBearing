    def query_with_expansion(
        self,
        text: str,
        max_results: int = 1,
        *,
        product: str | None = None,
    ) -> str:
        """
        TF-IDF query with synonym expansion for better short-step matching.

        Short AC steps like "Sort by Due Date" produce weak TF-IDF vectors
        because they contain few domain-specific terms.  This method expands
        the query text before scoring by appending synonym phrases for any
        recognised trigger words found in the step.

        The expansion is additive: ``original_text + expansion_terms``.
        This means precision is preserved (the original words still carry
        weight) while recall improves (the expanded terms boost score for
        articles that use the full domain vocabulary).

        For very short queries (< 10 words), expansion terms are appended
        twice (double-weight) to compensate for the mathematical disadvantage
        of having few terms in the TF-IDF query vector.

        Args
        ----
        text : str
            The current AC step text.
        max_results : int
            Maximum number of workflows to return.

        Returns
        -------
        str
            Formatted KB context block (same format as ``query()``).
        """
        if not text:
            return ""

        text_lower = text.lower()
        word_count = len(text.split())
        expansion_parts: list[str] = []

        for trigger, expansion in self._SYNONYM_MAP.items():
            if trigger in text_lower:
                expansion_parts.append(expansion)

        if expansion_parts:
            expansion_str = " ".join(expansion_parts)
            # Double-weight expansion for very short queries (< 10 words)
            # to compensate for the low term count in the query vector.
            if word_count < 10:
                expanded_text = text + " " + expansion_str + " " + expansion_str
                logger.debug(
                    "KB query_with_expansion: '%s' → +%d expansion phrase(s) [DOUBLE-WEIGHT, %d words]",
                    text[:50],
                    len(expansion_parts),
                    word_count,
                )
            else:
                expanded_text = text + " " + expansion_str
                logger.debug(
                    "KB query_with_expansion: '%s' → +%d expansion phrase(s)",
                    text[:50],
                    len(expansion_parts),
                )
        else:
            expanded_text = text

        return self.query(expanded_text, max_results=max_results, product=product)

    def reload_if_updated(self) -> bool:
        """
        Hot-reload the KB index if any .md file on disk has changed.

        Called at the top of every ``query()`` call. Compares the current
        mtime of each file against the recorded mtime at last load. If any
        file is newer (e.g. a human-takeover just appended to vSuite-actions.md),
        the full index is rebuilt.

        The mtime check is a single ``stat()`` syscall per file — negligible
        overhead when nothing has changed (~microseconds).

        Returns
        -------
        bool
            True if the index was reloaded, False if everything was up-to-date.
        """
        if not _KB_DIR.exists():
            return False

        # Include top-level KB files AND product-scoped subdirectories
        # (knowledge/<product>/*.md) so wf-*.md workflow updates under
        # knowledge/vpromotions/ trigger a hot reload just like global changes do.
        current_files: dict[str, float] = {
            str(p): p.stat().st_mtime for p in _KB_DIR.glob("*.md")
        }
        for subdir in _KB_DIR.iterdir():
            if subdir.is_dir():
                for md in subdir.glob("*.md"):
                    current_files[str(md)] = md.stat().st_mtime

        # Detect new files or modified files
        needs_reload = set(current_files.keys()) != set(self._file_mtimes.keys()) or any(
            current_files.get(p, 0) != self._file_mtimes.get(p, -1) for p in current_files
        )

        if needs_reload:
            changed = [Path(p).name for p, mtime in current_files.items() if mtime != self._file_mtimes.get(p, -1)]
            logger.info("KB hot-reload triggered: changed files = %s", changed)
            self.reload()
            return True

        return False

    def query_for_failure(
        self,
        ac_step: str,
        error_message: str,
        last_action: str = "",
        max_results: int = 2,
    ) -> str:
        """
        Targeted KB query when a step has failed.

        Combines the AC step text, the error message, and the last attempted
        action into a single richer query string.  This surfaces KB entries
        that wouldn't score above threshold for the plain step text alone —
        e.g. a "Timeout" error on a sort step finds the TABLE SORTING RULES
        even if the step text just says "Click CLIENT column header".

        Args
        ----
        ac_step : str
            The AC step text.
        error_message : str
            The error/failure message from the last executor attempt.
        last_action : str
            A short description of the last attempted action (optional).
        max_results : int
            Maximum number of KB workflows to return.

        Returns
        -------
        str
            Formatted KB context block, or empty string if no match.
        """
        # Build an enriched query: step + error keywords + action
        error_keywords = " ".join(error_message.lower().split()[:20])
        combined = f"{ac_step} {error_keywords} {last_action}".strip()
        result = self.query(combined, max_results=max_results)

        if result:
            # ── Prompt size guard: cap failure KB at 3,000 chars ────────────
            # query_for_failure uses max_results=2, so up to 2 uncapped articles
            # could stack. Combined cap prevents >~810 tokens from KB alone.
            _MAX_FAILURE_KB_CHARS = 3000
            if len(result) > _MAX_FAILURE_KB_CHARS:
                result = result[:_MAX_FAILURE_KB_CHARS] + "\n... [truncated]"
            # Prefix so the agent knows this is failure-specific guidance
            return (
                "═" * 63 + "\n"
                "⚠ KB FAILURE GUIDANCE (retrieved because this step just failed):\n"
                "Read carefully — this entry directly addresses the error above.\n" + "═" * 63 + "\n" + result
            )
        return ""

    # ── T3-a: Product-scoped workflow query ────────────────────────────────

    def query_workflows(
        self,
        text: str = "",
        *,
        product: str | None = None,
        max_results: int = 1,
    ) -> str:
        """
        T3-a — Product-scoped KB query (AC-VERIFY-2).

        When ``product`` is supplied, only workflows whose source file lives
        under ``knowledge/<product>/`` are considered — enforcing zero cross-product
        workflow bleed. Backward-compatible: omitting ``product`` gives global scope.
        """
        if not text:
            return ""

        if product is None:
            return self.query_with_expansion(text, max_results=max_results)

        product_kb_dir = _KB_DIR / product
        if not product_kb_dir.exists():
            logger.warning(
                "KB query_workflows: product dir '%s' does not exist — "
                "no product-scoped KB available for product=%s",
                product_kb_dir,
                product,
            )
            return ""

        scoped_kb = self._get_or_build_product_kb(product, product_kb_dir)
        return scoped_kb.query_with_expansion(text, max_results=max_results)

    def _get_or_build_product_kb(
        self,
        product: str,
        product_kb_dir: Path,
    ) -> "LocalKnowledgeBase":
        """T3-a: lazily build and cache a product-scoped KB instance.

        Shared by ``query()`` and ``query_workflows()`` so both use identical
        per-product indices and cache identity.
        """
        if not hasattr(self, "_product_kb_cache"):
            self._product_kb_cache: dict[str, "LocalKnowledgeBase"] = {}

        if product not in self._product_kb_cache:
            scoped_kb = LocalKnowledgeBase.__new__(LocalKnowledgeBase)
            scoped_kb._workflows = []
            scoped_kb._vectorizer = None
            scoped_kb._tfidf_matrix = None
            scoped_kb._bm25 = None
            scoped_kb._bm25_corpus = []
            scoped_kb._file_mtimes = {}
            scoped_kb._query_cache = {}
            # Tag the scoped instance with the product it was built for. Its
            # own query() consults this at Phase -1 to filter the Chroma
            # human_guidance_vault; without it, Phase -1 would leak stale
            # cross-product HITL captures back into product-scoped results.
            scoped_kb._scoped_product = product

            md_files = list(product_kb_dir.glob("*.md"))
            for path in md_files:
                scoped_kb._file_mtimes[str(path)] = path.stat().st_mtime
                if path.name in _CHUNKED_FILES:
                    scoped_kb._load_chunked_file(path)
                else:
                    scoped_kb._load_file(path)

            scoped_kb._build_index()
            self._product_kb_cache[product] = scoped_kb
            logger.info(
                "KB: built product-scoped index for '%s' (%d workflows from %d files)",
                product,
                len(scoped_kb._workflows),
                len(md_files),
            )

        return self._product_kb_cache[product]

    def reload(self) -> None:
        """Reload all KB files from disk (useful after KB promotion or development)."""
        self._workflows.clear()
        self._file_mtimes.clear()
        self._query_cache.clear()
        self._bm25 = None
        self._bm25_corpus.clear()
        if hasattr(self, "_product_kb_cache"):
            self._product_kb_cache.clear()
        self._load_all()
        self._build_index()


