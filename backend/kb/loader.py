"""
vQA — Local Knowledge Base Loader (TF-IDF Enhanced)
=====================================================
Module: backend/kb/loader.py

Loads Markdown knowledge base files from the ``knowledge/`` directory
at startup and provides TF-IDF-based semantic retrieval for the planner.

The planner calls ``kb.query(ac_step_text)`` before building its prompt.
If a relevant workflow is found above the relevance threshold, its
instructions are prepended to the system prompt.

Why TF-IDF (not vector/LLM retrieval)?
- TF-IDF captures bigrams like "quick order", "production notes"
- Cosine similarity provides a numerical relevance score with threshold
- No API call needed — instant and deterministic
- scikit-learn's TF-IDF is battle-tested and handles edge cases

File Loading Strategy
---------------------
  Standard files (## WORKFLOW: format):
      Loaded as-is via _load_file(). Each ## WORKFLOW: section = 1 document.

  Chunked files (knowledge_base_manuals.md from kb_formatter.py):
      Split on "## Standardized Task Name:" headers.
      Each section = 1 individually-indexed KBWorkflow.
      This converts the 416KB monolith into ~100 searchable docs.

Format of standard KB files:
  ## WORKFLOW: <name>
  KEYWORDS: <comma-separated trigger words>
  ---
  <step-by-step instructions>

Usage in planner:
  from backend.kb.loader import kb
  hint = kb.query(current_ac_step)
  if hint:
      system_prompt += f"\\n{hint}"
"""

import logging
import re
from pathlib import Path

import numpy as np
from rank_bm25 import BM25Okapi
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

from backend.kb.rag import human_guidance_vault

logger = logging.getLogger(__name__)

# Path to the knowledge directory (relative to project root)
_KB_DIR = Path(__file__).parent.parent.parent / "knowledge"

# Files to EXCLUDE from loading entirely
# NOTE: vpromedia-workflows.md was previously excluded as "noise" but it contains
# critical voice workflow, login, status, and other domain knowledge (96 workflows).
# The TF-IDF relevance scoring (dynamic threshold 0.10-0.25) handles noise filtering.
_EXCLUDED_FILES: set[str] = set()

# Files to load via chunked parsing (split on standardized headers)
# These are generated by kb_formatter.py and have "## Standardized Task Name:" headers
_CHUNKED_FILES: set[str] = {"knowledge_base_manuals.md"}

# Domain-specific nouns used to compute dynamic relevance thresholds.
# Steps mentioning these words are treated as more specific and require
# a higher similarity score before KB context is injected.
_DOMAIN_NOUNS: frozenset[str] = frozenset(
    {
        "quick",
        "order",
        "qo",
        "spot",
        "prf",
        "commercial",
        "producer",
        "login",
        "radio",
        "client",
        "campaign",
        "endorsement",
        "draft",
        "script",
        "status",
        "approve",
        "submit",
        "upload",
        "production",
        "fulfillment",
        "dubber",
        "blueprint",
        "liner",
        "alps",
        "quu",
        "marketron",
        "wideorbit",
        "blog",
        "poc",
        "delegate",
    }
)


class KBWorkflow:
    """A single parsed workflow from a KB Markdown file."""

    def __init__(self, name: str, keywords: list[str], instructions: str):
        self.name = name
        self.keywords = [k.strip().lower() for k in keywords if k.strip()]
        self.instructions = instructions.strip()
        self.forbidden_keywords: list[str] = []  # FEAT-006: negative filter


class LocalKnowledgeBase:
    """
    TF-IDF-indexed knowledge base loaded from Markdown files.

    Loaded once at module import time. Call ``query(text)`` to retrieve
    the most relevant workflow instructions for a given AC step.

    Two loading strategies:
      1. _load_file(): parses standard ## WORKFLOW: format files
      2. _load_chunked_file(): parses knowledge_base_manuals.md into
         ~100 per-workflow chunks using ## Standardized Task Name: headers

    The relevance threshold is computed dynamically per-query based on
    step domain-specificity, preventing generic steps from pulling
    irrelevant KB context.
    """

    def __init__(self):
        self._workflows: list[KBWorkflow] = []
        self._vectorizer: TfidfVectorizer | None = None
        self._tfidf_matrix = None
        self._bm25: BM25Okapi | None = None
        self._bm25_corpus: list[list[str]] = []
        self._file_mtimes: dict[str, float] = {}  # path str → mtime at last load
        self._query_cache: dict[str, str] = {}  # expanded_text::max_results → result
        self._load_all()
        self._build_index()

    # ── Threshold ──────────────────────────────────────────────────────────

    def _compute_threshold(self, text: str) -> float:
        """
        Compute a relevance threshold based on how domain-specific the query is.

        Domain-specific steps (many _DOMAIN_NOUNS) need a higher match score
        before KB context is injected — a strong specific match is meaningful.
        Generic steps get a lower threshold so something useful can still be found.

        Short queries (< 15 words) get a lower floor (0.06 instead of 0.10)
        because fewer terms produce inherently weaker TF-IDF cosine scores.

        Product-scoped KB instances (built via _get_or_build_product_kb) run
        against a much smaller corpus and are already filtered to relevant
        product content — a related workflow is far more useful than nothing,
        so they get a lower floor.

        Returns a value in [0.03, 0.25].
        """
        words = set(text.lower().split())
        word_count = len(text.split())
        domain_word_count = len(words & _DOMAIN_NOUNS)
        # Short queries get a lower floor to compensate for low term frequency
        floor = 0.06 if word_count < 15 else 0.10
        # Product-scoped KBs return a related workflow > nothing
        if getattr(self, "_scoped_product", None):
            floor = max(0.03, floor - 0.05)
        # 0 domain words → floor (permissive)
        # 1 domain word  → floor + 0.05
        # 2+             → floor + 0.10..0.15 capped
        specificity_boost = min(domain_word_count * 0.05, 0.15)
        return round(floor + specificity_boost, 2)

    # ── File Loading ───────────────────────────────────────────────────────

    def _load_all(self) -> None:
        """Load all .md files from the knowledge directory and record their mtimes."""
        if not _KB_DIR.exists():
            logger.warning("KB directory not found: %s", _KB_DIR)
            return

        # human_guidance.md is created on first user interaction and hot-reloaded
        # automatically — no explicit registration needed, it's covered by *.md glob.
        md_files = list(_KB_DIR.glob("*.md"))
        if not md_files:
            logger.warning("No .md files found in KB directory: %s", _KB_DIR)
            return

        loaded_count = 0
        chunked_count = 0
        excluded_count = 0

        for path in md_files:
            # Record mtime for hot-reload detection
            self._file_mtimes[str(path)] = path.stat().st_mtime

            if path.name == "human_guidance.md":
                # Exclude from standard workflows list because it will be loaded into HumanGuidanceVault
                continue

            if path.name in _EXCLUDED_FILES:
                logger.info("KB: EXCLUDED '%s' (noise file)", path.name)
                excluded_count += 1
            elif path.name in _CHUNKED_FILES:
                before = len(self._workflows)
                self._load_chunked_file(path)
                chunked_count += len(self._workflows) - before
            else:
                self._load_file(path)
                loaded_count += 1

        # Record mtimes for product-scoped KB files too (knowledge/<product>/*.md).
        # The actual workflows are lazy-loaded per product on first query()
        # via _get_or_build_product_kb — but we still need the mtimes here so
        # reload_if_updated() detects changes to wf-*.md files under a
        # product subdirectory and triggers a full reload (which also clears
        # _product_kb_cache).
        for subdir in _KB_DIR.iterdir():
            if not subdir.is_dir():
                continue
            for md in subdir.glob("*.md"):
                self._file_mtimes[str(md)] = md.stat().st_mtime

        # Index human_guidance.md in HumanGuidanceVault
        guidance_path = _KB_DIR / "human_guidance.md"
        if guidance_path.exists():
            from backend.kb.rag import human_guidance_vault
            try:
                human_guidance_vault.index_guidance_file(guidance_path)
            except Exception as e:
                logger.error("Failed to index human_guidance.md in HumanGuidanceVault: %s", e)

        logger.info(
            "Knowledge base loaded: %d workflow(s) total "
            "(%d from standard files, %d from chunked manual, %d file(s) excluded)",
            len(self._workflows),
            loaded_count,
            chunked_count,
            excluded_count,
        )

    def _load_file(self, path: Path) -> None:
        """Parse a single Markdown KB file into KBWorkflow objects (standard format)."""
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as e:
            logger.error("Failed to read KB file %s: %s", path, e)
            return

        # Split on workflow headers: ## WORKFLOW: <name>
        sections = re.split(r"^## WORKFLOW:", text, flags=re.MULTILINE)

        for section in sections[1:]:  # skip preamble
            lines = section.strip().split("\n")
            if not lines:
                continue

            name = lines[0].strip()

            # Find KEYWORDS, FORBIDDEN_KEYWORDS, and --- separator
            keywords: list[str] = []
            forbidden_keywords: list[str] = []
            body_start = 1
            for i, line in enumerate(lines[1:], 1):
                stripped = line.strip()
                if stripped.startswith("KEYWORDS:"):
                    keywords = stripped.removeprefix("KEYWORDS:").split(",")
                elif stripped.startswith("FORBIDDEN_KEYWORDS:"):
                    forbidden_keywords = [
                        k.strip().lower() for k in stripped.removeprefix("FORBIDDEN_KEYWORDS:").split(",") if k.strip()
                    ]
                elif stripped == "---":
                    body_start = i + 1
                    break

            instructions = "\n".join(lines[body_start:]).strip()
            if not instructions:
                continue

            workflow = KBWorkflow(name=name, keywords=keywords, instructions=instructions)
            workflow.forbidden_keywords = forbidden_keywords
            self._workflows.append(workflow)
            logger.debug(
                "KB: loaded workflow '%s' (%d keywords, %d forbidden)", name, len(keywords), len(forbidden_keywords)
            )

    def _load_chunked_file(self, path: Path) -> None:
        """
        Parse a large KB manual (from kb_formatter.py) into per-workflow chunks.

        Splits on "## Standardized Task Name:" headers. Each section becomes
        an individually-indexed KBWorkflow. This converts the 416KB monolith
        into ~100 searchable documents.

        For each chunk we extract:
          - name: the task name (first line after the header)
          - keywords: the "Trigger Phrases & Jira Aliases" bullet list
          - instructions: the "Step-by-Step Execution Guide" section
        """
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as e:
            logger.error("Failed to read chunked KB file %s: %s", path, e)
            return

        # Split on the standardized header generated by kb_formatter.py
        sections = re.split(r"^## Standardized Task Name:", text, flags=re.MULTILINE)
        loaded = 0

        for section in sections[1:]:
            lines = section.strip().split("\n")
            if not lines:
                continue

            name = lines[0].strip()
            if not name:
                continue

            # ── Extract Trigger Phrases (keyword aliases) ────────────────
            keywords: list[str] = []
            kw_match = re.search(
                r"### Trigger Phrases.*?\n(.*?)###",
                section,
                re.DOTALL,
            )
            if kw_match:
                kw_block = kw_match.group(1)
                keywords = [
                    ln.strip().lstrip("- ").lower() for ln in kw_block.strip().split("\n") if ln.strip().startswith("-")
                ]

            # ── Extract Step-by-Step Execution Guide ────────────────────
            # This is the most actionable content for the planner
            steps_match = re.search(
                r"### Step-by-Step Execution Guide\n(.*?)(?=###|\Z)",
                section,
                re.DOTALL,
            )
            instructions = steps_match.group(1).strip() if steps_match else ""

            if not instructions or len(instructions) < 50:
                # Fallback to Task Objective if no steps found
                obj_match = re.search(
                    r"### Task Objective\n(.*?)(?=###|\Z)",
                    section,
                    re.DOTALL,
                )
                instructions = obj_match.group(1).strip() if obj_match else ""

            if not instructions:
                continue

            # Truncate to avoid bloating the planner prompt
            instructions = instructions[:1000]

            workflow = KBWorkflow(name=name, keywords=keywords, instructions=instructions)
            self._workflows.append(workflow)
            loaded += 1

        logger.info("KB: loaded %d chunked workflows from '%s'", loaded, path.name)

    # ── Index ──────────────────────────────────────────────────────────────

    def _build_index(self) -> None:
        """Build TF-IDF and BM25 indices from loaded workflows."""
        if not self._workflows:
            logger.info("KB: no workflows to index")
            return

        # Build a corpus where each document combines the workflow's
        # name, keywords, and instructions for maximum matching surface
        corpus = [f"{w.name} {' '.join(w.keywords)} {w.instructions}" for w in self._workflows]

        # ── TF-IDF index ──────────────────────────────────────────────────
        self._vectorizer = TfidfVectorizer(
            stop_words="english",
            ngram_range=(1, 2),  # bigrams catch "quick order", "production notes"
            max_features=10000,  # increased from 5000 to handle larger corpus
        )
        self._tfidf_matrix = self._vectorizer.fit_transform(corpus)

        # ── BM25 index (FEAT-006) ─────────────────────────────────────────
        # Tokenize each document into lowercase words for BM25Okapi.
        # BM25 handles term frequency saturation better than TF-IDF cosine,
        # improving recall for short queries with rare but important terms.
        self._bm25_corpus = [doc.lower().split() for doc in corpus]
        self._bm25 = BM25Okapi(self._bm25_corpus)

        logger.info(
            "KB TF-IDF + BM25 index built: %d documents, %d TF-IDF features",
            self._tfidf_matrix.shape[0],
            self._tfidf_matrix.shape[1],
        )

    # ── Query ──────────────────────────────────────────────────────────────

    def query(
        self,
        text: str,
        max_results: int = 1,
        *,
        product: str | None = None,
    ) -> str:
        """
        Find the most relevant workflow(s) for the given AC step text.

        Retrieval phases (in order):
          Phase 0: Exact-match shortcut for AUTO-LEARNED entries (deterministic).
          Phase 1: TF-IDF cosine similarity with dynamic threshold (fuzzy).

        Results are cached per (text, max_results) and cleared on KB reload.

        Args
        ----
        text : str
            The current AC step or user guidance text to match against.
        max_results : int
            Maximum number of workflows to return (default 1).
        product : str | None
            T3-a — when provided, restrict retrieval to workflows whose source
            file lives under ``knowledge/<product>/``. Omitting keeps global
            scope (backward-compatible).

        Returns
        -------
        str
            Formatted KB context block ready to inject into a prompt.
            Empty string if no workflows match above the threshold.
        """
        # T3-a: route product-scoped queries through the per-product KB cache
        # (same cache/build path used by query_workflows). The scoped KB's own
        # query() call passes product=None so the routing is not recursive —
        # but the semantic Chroma vault below still needs the product tag
        # forwarded so it doesn't pull in cross-product HITL entries.
        if product is not None:
            product_kb_dir = _KB_DIR / product
            if not product_kb_dir.exists():
                logger.warning(
                    "KB query: product dir '%s' does not exist — "
                    "no product-scoped KB available for product=%s",
                    product_kb_dir,
                    product,
                )
                return ""
            scoped_kb = self._get_or_build_product_kb(product, product_kb_dir)
            scoped_result = scoped_kb.query(text, max_results=max_results)
            if scoped_result:
                return scoped_result
            # Fall through: TF-IDF miss on the product-scoped KB. Try the
            # Chroma vault next, restricted to entries tagged with this
            # product OR global-neutral. This preserves useful HITL captures
            # while blocking cross-product leakage.
            try:
                guidance_matches = human_guidance_vault.query(
                    text,
                    max_results=max_results,
                    distance_threshold=0.7,
                    product=product,
                )
                if guidance_matches:
                    # Same quality gate as Phase -1 above: drop low-value
                    # HITL captures so we don't prefer them over the
                    # source-cited product-scoped TF-IDF result.
                    def _hitl_is_actionable(m: dict) -> bool:
                        instr = (m.get("instructions") or "").strip()
                        if len(instr) < 200:
                            return False
                        if "(no DOM actions captured)" in instr and len(instr) < 600:
                            return False
                        return True
                    guidance_matches = [m for m in guidance_matches if _hitl_is_actionable(m)]
                if guidance_matches:
                    workflows = [
                        KBWorkflow(name=m["title"], keywords=m["keywords"], instructions=m["instructions"])
                        for m in guidance_matches
                    ]
                    logger.info(
                        "KB semantic RAG match (product=%s): %d workflow(s) from human_guidance_vault",
                        product, len(workflows),
                    )
                    return self._format_result(workflows)
            except Exception as e:
                logger.error("Failed to query HumanGuidanceVault (product=%s): %s", product, e)
            return ""

        if not text or self._vectorizer is None or self._tfidf_matrix is None:
            return ""

        cache_key = f"{text}::{max_results}"
        if cache_key in self._query_cache:
            return self._query_cache[cache_key]

        # ── Phase -1: Dense Semantic Embeddings for Guidance (ChromaDB) ────
        # When this LocalKnowledgeBase instance was built for a specific
        # product (see _get_or_build_product_kb), forward that scope to
        # the vault so its results honor the same product boundary. Without
        # this, a scoped-KB query can return cross-product HITL matches.
        _phase_minus_1_product = getattr(self, "_scoped_product", None)
        try:
            guidance_matches = human_guidance_vault.query(
                text,
                max_results=max_results,
                distance_threshold=0.7,
                product=_phase_minus_1_product,
            )
            # Quality gate: some HITL captures have no DOM actions and only a
            # one-line prose explanation ("clicked the category dropdown").
            # Those entries win Chroma retrieval on semantic similarity but
            # provide no executable instructions AND may encode a strategy
            # that later proved wrong. Skip Phase -1 for such entries so the
            # downstream TF-IDF path (which retrieves the source-cited
            # wf-*.md files) gets to answer instead.
            def _hitl_is_actionable(m: dict) -> bool:
                instr = (m.get("instructions") or "").strip()
                if len(instr) < 200:
                    return False
                # Well-formed HITL entries with real DOM actions list them
                # verbatim in the instructions body. "(no DOM actions
                # captured)" is the marker for the low-value auto-generated
                # explanation-only entries.
                if "(no DOM actions captured)" in instr and len(instr) < 600:
                    return False
                return True
            if guidance_matches:
                guidance_matches = [m for m in guidance_matches if _hitl_is_actionable(m)]
            if guidance_matches:
                workflows = []
                for m in guidance_matches:
                    wf = KBWorkflow(
                        name=m["title"],
                        keywords=m["keywords"],
                        instructions=m["instructions"]
                    )
                    workflows.append(wf)
                logger.info("KB semantic RAG match: Found %d relevant workflows in human_guidance_vault", len(workflows))
                result = self._format_result(workflows)
                self._query_cache[cache_key] = result
                return result
        except Exception as e:
            logger.error("Failed to query HumanGuidanceVault: %s", e)

        # ── Phase 0: Exact-match shortcut for AUTO-LEARNED entries ────────
        # AUTO-LEARNED workflows use the exact AC step text as their name.
        # A normalized string comparison provides deterministic, zero-ambiguity
        # retrieval that TF-IDF cannot achieve for near-identical sort steps.
        query_step = text.strip().lower()
        for wf in self._workflows:
            if wf.name.startswith("AUTO-LEARNED"):
                wf_step = wf.name.replace("AUTO-LEARNED — ", "").strip().lower()
                if wf_step == query_step or query_step.startswith(wf_step):
                    logger.info(
                        "KB exact-match: '%s' → INJECTED (Phase 0, skipping TF-IDF)",
                        wf.name[:80],
                    )
                    return self._format_result([wf])

        # ── Phase 1: TF-IDF cosine similarity + BM25 re-ranking ──────────
        threshold = self._compute_threshold(text)

        # Transform the query text into the same TF-IDF space
        query_vec = self._vectorizer.transform([text])
        tfidf_scores = cosine_similarity(query_vec, self._tfidf_matrix).flatten()

        # Get top-10 TF-IDF candidates for BM25 re-ranking
        _RERANK_POOL_SIZE = 10
        top_indices = np.argsort(tfidf_scores)[::-1][:_RERANK_POOL_SIZE]

        # ── BM25 re-ranking (FEAT-006) ────────────────────────────────────
        # Score the top-10 TF-IDF candidates with BM25 and compute a
        # combined score: 0.6 * tfidf + 0.4 * bm25_normalized.
        # BM25 boosts ranking for long-tail terms; threshold gating still
        # uses the raw TF-IDF score to avoid false positives.
        if self._bm25 is not None:
            query_tokens = text.lower().split()
            bm25_all_scores = self._bm25.get_scores(query_tokens)
            # Normalize BM25 scores to [0, 1] range
            bm25_max = bm25_all_scores.max() if bm25_all_scores.max() > 0 else 1.0
            bm25_normalized = bm25_all_scores / bm25_max

            # Compute combined scores for the top-10 candidates
            combined = []
            for idx in top_indices:
                tfidf_s = tfidf_scores[idx]
                bm25_s = bm25_normalized[idx]
                combined_score = 0.6 * tfidf_s + 0.4 * bm25_s
                combined.append((combined_score, tfidf_s, idx))

            # Re-sort by combined score descending
            combined.sort(key=lambda x: -x[0])
            # Take top max_results after re-ranking
            reranked = combined[:max_results]
        else:
            # Fallback: no BM25, use TF-IDF order directly
            reranked = [(tfidf_scores[idx], tfidf_scores[idx], idx) for idx in top_indices[:max_results]]

        # Filter by dynamic threshold — only inject if match is meaningful
        # Threshold is applied to the RAW TF-IDF score (not combined) to
        # avoid BM25 boosting noise past the gate.
        results: list[KBWorkflow] = []
        for combined_score, tfidf_score, idx in reranked:
            wf = self._workflows[idx]
            # Human-guidance entries (written by HITL takeover) are tagged with
            # 'human-guidance' in their keywords.  These entries have high phrasing
            # variance vs. the query, so we use a much lower fixed threshold (0.05)
            # instead of the domain-adaptive 0.06-0.25 range.
            is_hitl_entry = (
                "human-guidance" in wf.keywords
                or "human-guidance" in wf.name.lower()
                or "ui-paradigm" in wf.keywords
                or "paradigm" in wf.keywords
            )
            effective_threshold = 0.05 if is_hitl_entry else threshold
            if tfidf_score >= effective_threshold:
                # ── FORBIDDEN_KEYWORDS filter (FEAT-006) ──────────────────
                # If this workflow has forbidden keywords and the query text
                # contains any of them, skip it to prevent cross-polarity
                # misretrievals (e.g., "login success" article for "login fails").
                if wf.forbidden_keywords:
                    query_lower = text.lower()
                    blocked_by = [fk for fk in wf.forbidden_keywords if fk in query_lower]
                    if blocked_by:
                        logger.debug(
                            "KB match: '%s' tfidf=%.3f → BLOCKED by FORBIDDEN_KEYWORDS %s",
                            wf.name,
                            tfidf_score,
                            blocked_by,
                        )
                        continue
                results.append(wf)
                logger.debug(
                    "KB match: '%s' tfidf=%.3f bm25_combined=%.3f (threshold=%.2f%s) → INJECTED",
                    wf.name,
                    tfidf_score,
                    combined_score,
                    effective_threshold,
                    " [HITL-bypass]" if is_hitl_entry else "",
                )
            else:
                logger.debug(
                    "KB match: '%s' tfidf=%.3f bm25_combined=%.3f (threshold=%.2f) → SKIPPED",
                    wf.name,
                    tfidf_score,
                    combined_score,
                    threshold,
                )

        if not results:
            # ── KB gate closure diagnostic (FEAT-006) ─────────────────────
            top_tfidf = tfidf_scores[top_indices[0]] if len(top_indices) > 0 else 0.0
            top_name = self._workflows[top_indices[0]].name[:40] if len(top_indices) > 0 else "N/A"
            logger.info(
                "KB gate OPEN but NO MATCH — step '%s' | threshold=%.2f | top_score=%.3f | top_name='%s'",
                text[:60],
                threshold,
                top_tfidf,
                top_name,
            )
            self._query_cache[cache_key] = ""
            return ""

        result = self._format_result(results)
        self._query_cache[cache_key] = result
        return result

    def _format_result(self, results: list["KBWorkflow"]) -> str:
        """Format a list of KBWorkflow results into a prompt-ready string."""
        # ── Prompt size guard: cap each article ────────────────────────────
        # Standard KB files have no per-workflow char limit — a single article
        # can be up to 12,972 chars (observed: Compact View Navigation article).
        # Capping at 2,000 chars keeps the injected block under ~540 tokens while
        # still covering the actionable step-by-step content at the top of each
        # article (the "what to do" section always leads; footnotes trail).
        _MAX_ARTICLE_CHARS = 2000

        sections = []
        for workflow in results:
            inst = workflow.instructions
            truncated = ""
            if len(inst) > _MAX_ARTICLE_CHARS:
                inst = inst[:_MAX_ARTICLE_CHARS]
                truncated = "\n... [article truncated at 2,000 chars — key steps above]"
            sections.append(f"[KB: {workflow.name}]\n{inst}{truncated}")

        joined = "\n\n---\n\n".join(sections)
        return (
            "═══════════════════════════════════════════════════════════════\n"
            "KNOWLEDGE BASE — vSuite Expert Instructions:\n"
            "(Use these step-by-step instructions to guide your action)\n"
            "═══════════════════════════════════════════════════════════════\n"
            + joined
            + "\n════════════════════════════════════════════════════════════════"
        )

