"""
vQA — Selector Registry
========================
Module: backend/kb/selector_registry.py

Loads ground-truth confirmed Playwright selectors from
knowledge/selector_registry.json and provides keyword-matched lookup
for the planner.

Unlike the TF-IDF KB which matches workflow *instructions*, this registry
matches known UI *elements* and returns their confirmed-working Playwright
locator strategies. The planner injects these BEFORE guessing from the
accessibility tree, eliminating selector hallucination on known elements.

Source of Truth
---------------
selector_registry.json is generated by scripts/extract_playwright_kb.py
which extracts locators from the vsuitePlatform Playwright branch:
  - playwright/utils/OrderHelper.ts
  - playwright/utils/NavHelper.ts
  - playwright/utils/QO_helpers.ts

To regenerate after new Playwright tests are added:
  make kb-refresh

Usage
-----
    from backend.kb.selector_registry import selector_registry

    hints = selector_registry.query("Submit the quick order form")
    if hints:
        system_prompt += f"\\n{hints}"

See Also
--------
    - backend/engine/planner.py — consumes selector hints
    - knowledge/selector_registry.json — the data source
    - scripts/extract_playwright_kb.py — the generator script
"""

import json
import logging
import re
import threading
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger(__name__)

_REGISTRY_PATH = Path(__file__).parent.parent.parent / "knowledge" / "selector_registry.json"

# Words too generic to use for matching
_STOP_WORDS: frozenset[str] = frozenset(
    {
        "the",
        "a",
        "an",
        "and",
        "or",
        "is",
        "in",
        "on",
        "to",
        "from",
        "that",
        "this",
        "it",
        "with",
        "of",
        "for",
        "by",
        "at",
        "as",
        "be",
        "are",
        "was",
        "i",
        "if",
        "then",
        "should",
        "not",
        "no",
        "click",
        "verify",
        "check",
        "confirm",
        "navigate",
        "open",
        "ensure",
        "make",
        "see",
        "go",
        "get",
        "set",
        "view",
    }
)


class SelectorRegistry:
    """
    Ground-truth selector registry loaded from JSON.

    Call ``query(ac_step_text)`` to get matching selector hints for
    the current AC step. Results are formatted for injection into the
    planner system prompt.
    """

    def __init__(self):
        self._selectors: dict = {}
        self._lock = threading.Lock()
        self._load()

    def _load(self) -> None:
        """Load the registry from JSON. Logs a warning if not found (non-fatal)."""
        if not _REGISTRY_PATH.exists():
            logger.warning(
                "Selector registry not found at %s — run 'make kb-refresh' to generate it from the Playwright branch.",
                _REGISTRY_PATH,
            )
            return
        try:
            data = json.loads(_REGISTRY_PATH.read_text(encoding="utf-8"))
            self._selectors = data.get("selectors", {})
            logger.info(
                "Selector registry loaded: %d entries (v%s, updated %s)",
                len(self._selectors),
                data.get("version", "?"),
                data.get("last_updated", "?"),
            )
        except (json.JSONDecodeError, OSError) as e:
            logger.error("Failed to load selector registry: %s", e)

    def query(self, ac_step_text: str, max_results: int = 3) -> str:
        """
        Find confirmed selectors relevant to the current AC step.

        Uses keyword overlap scoring against each entry's description
        and context fields. Returns the top ``max_results`` matches.

        Args
        ----
        ac_step_text : str
            The current AC step text to match against.
        max_results : int
            Maximum number of registry entries to return.

        Returns
        -------
        str
            Formatted selector hint block ready for prompt injection.
            Empty string if no matches found or registry is empty.
        """
        if not ac_step_text or not self._selectors:
            return ""

        step_words = self._meaningful_words(ac_step_text)
        if not step_words:
            return ""

        matches: list[tuple[int, str, dict]] = []
        for key, entry in self._selectors.items():
            combined = f"{entry.get('description', '')} {entry.get('context', '')}".lower()
            overlap = sum(1 for w in step_words if w in combined)
            if overlap >= 2:
                matches.append((overlap, key, entry))

        if not matches:
            return ""

        matches.sort(key=lambda x: -x[0])
        top = matches[:max_results]

        lines = [
            "\n\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550",
            "\ud83c\udfaf SELECTOR REGISTRY \u2014 Ground-Truth Locators (Use FIRST before guessing):",
            "\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550",
        ]

        for _, key, entry in top:
            lines.append(f"\n  [{entry.get('description', key)}]")
            strategies = entry.get("strategies", [])
            for s in strategies[:2]:
                method = s.get("method", "")
                if method == "get_by_role":
                    lines.append(
                        f'  \u2192 strategy: "get_by_role", role: "{s.get("role", "")}", name: "{s.get("name", "")}"'
                    )
                elif method == "get_by_text":
                    lines.append(f'  \u2192 strategy: "get_by_text", name: "{s.get("name", "")}"')
                elif method == "css":
                    lines.append(f'  \u2192 strategy: "css_selector", selector: "{s.get("selector", "")}"')
                elif method == "get_by_placeholder":
                    lines.append(f'  \u2192 strategy: "get_by_placeholder", name: "{s.get("name", "")}"')
                elif method == "get_by_label":
                    lines.append(f'  \u2192 strategy: "get_by_label", name: "{s.get("name", "")}"')

            if entry.get("timing_note"):
                lines.append(f"  \u23f1 Timing: {entry['timing_note']}")
            if entry.get("context"):
                lines.append(f"  \u2139 Context: {entry['context']}")

        lines.append(
            "\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550\u2550"
        )
        return "\n".join(lines)

    def _meaningful_words(self, text: str) -> set[str]:
        """Extract non-trivial words for overlap matching."""
        return {w for w in text.lower().split() if w not in _STOP_WORDS and len(w) > 3}

    def lookup(
        self,
        product_slug: str,
        ac_step_text: str,
        target_name: str = "",
    ) -> dict | None:
        """
        Product-scoped deterministic registry lookup for T3-b RegistryFirstGate.

        Checks ``selectors[product_slug]`` for an entry whose ``ac_step_patterns``
        list contains a regex that matches ``ac_step_text``. Returns the entry's
        action fields on a hit, or ``None`` on a miss.

        This differs from ``query()`` (which searches all entries and returns a
        formatted prompt string) — ``lookup()`` is a hard gate that returns
        structured data for action rewriting.

        Args
        ----
        product_slug : str
            Active product slug (e.g. "vpromotions"). Only the product's
            sub-namespace under ``selectors`` is searched.
        ac_step_text : str
            Current AC step text to match against each entry's
            ``ac_step_patterns`` regexes.
        target_name : str
            Optional element target name for fallback exact-match
            (used when ac_step_patterns is absent on legacy entries).

        Returns
        -------
        dict | None
            On hit: ``{playwright_strategy, role, name, vqa_id}`` (may omit
            role/vqa_id if not present in the entry). On miss: ``None``.
        """
        product_entries = self._selectors.get(product_slug)
        if not product_entries or not isinstance(product_entries, dict):
            return None

        for _key, entry in product_entries.items():
            patterns = entry.get("ac_step_patterns", [])
            for pattern in patterns:
                try:
                    if re.search(pattern, ac_step_text, re.IGNORECASE):
                        return {
                            "playwright_strategy": entry.get("playwright_strategy", "get_by_role"),
                            "role": entry.get("role"),
                            "name": entry.get("name", target_name),
                            "vqa_id": entry.get("vqa_id"),
                        }
                except re.error:
                    logger.warning(
                        "selector_registry: invalid pattern %r in entry %r — skipping",
                        pattern,
                        _key,
                    )
                    continue

        return None

    def get_all_entries(self) -> dict:
        """
        Return a copy of all selector entries for offline index build.

        Called by SelectorRAG.build_index() to construct the TF-IDF + BM25
        corpus.  Returns a snapshot — callers should not modify the returned
        dict (changes will not be persisted).

        Returns
        -------
        dict
            Mapping of selector_key → entry dict.  Empty dict if the
            registry has not been loaded or is empty.
        """
        return dict(self._selectors)

    def reload(self) -> None:
        """Reload the registry from disk (for testing and kb-refresh)."""
        with self._lock:
            self._selectors.clear()
        self._load()

    # ── Write Methods (HITL + Verified) ─────────────────────────────────

    def record_hitl_selector(
        self,
        description: str,
        selector: str,
        strategy: str,
        context: str = "",
        role: str = "",
        name: str = "",
    ) -> str:
        """
        Persist a selector confirmed by a human during HITL takeover.

        Called by human_takeover.py after the user's browser click log
        is parsed.  Writes a new entry (or updates existing) in
        selector_registry.json so all future planners see it.

        Args
        ----
        description : str
            Human-readable label, e.g. 'Sort By dropdown in Compact view'.
        selector : str
            The CSS selector or text, e.g. 'p-select#header-sort-drop-down'.
        strategy : str
            Playwright method: 'css_selector', 'get_by_text', 'get_by_role', etc.
        context : str
            Where this element appears (page, view, or workflow context).
        role : str
            ARIA role if strategy is get_by_role.
        name : str
            Text name if strategy is get_by_text or get_by_role.

        Returns
        -------
        str
            The registry key for the stored entry.
        """
        if not description or not selector:
            return ""

        # Derive a stable key from the description
        key = re.sub(r"[^a-z0-9_]+", "_", description.lower().strip())[:60].strip("_")

        now_iso = datetime.now(timezone.utc).isoformat()

        # Map strategy string to registry 'method' field
        method_map = {
            "css_selector": "css",
            "get_by_text": "get_by_text",
            "get_by_role": "get_by_role",
            "get_by_placeholder": "get_by_placeholder",
            "get_by_label": "get_by_label",
        }
        method = method_map.get(strategy, "css")

        strategy_entry: dict = {"method": method}
        if method == "css":
            strategy_entry["selector"] = selector
        elif method in ("get_by_text", "get_by_label", "get_by_placeholder"):
            strategy_entry["name"] = name or selector
        elif method == "get_by_role":
            strategy_entry["role"] = role
            strategy_entry["name"] = name or selector

        with self._lock:
            if key in self._selectors:
                # Update existing: prepend new strategy if not already present
                existing_strategies = self._selectors[key].get("strategies", [])
                existing_selectors = [s.get("selector") or s.get("name") for s in existing_strategies]
                if selector not in existing_selectors and (name or selector) not in existing_selectors:
                    existing_strategies.insert(0, strategy_entry)  # HITL strategies go first
                self._selectors[key]["hitl_confirmed"] = True
                self._selectors[key]["last_confirmed"] = now_iso
            else:
                self._selectors[key] = {
                    "description": description,
                    "strategies": [strategy_entry],
                    "context": context,
                    "hitl_confirmed": True,
                    "first_seen": now_iso,
                    "last_confirmed": now_iso,
                    "timing_note": None,
                }
            self._save()

        logger.info(
            "Selector registry: HITL-confirmed '%s' → strategy=%s selector=%s",
            key,
            strategy,
            selector[:60],
        )
        return key

    def record_verified_selector(
        self,
        ac_step_text: str,
        strategy: str,
        name: str,
        selector: str = "",
        role: str = "",
        context: str = "",
    ) -> str:
        """
        Persist a selector that was verified by the step_verifier (SATISFIED).

        Called by the evaluator after a step passes. Only records
        non-trivial selectors (css_selector or get_by_role/text with
        a meaningful name) to avoid polluting the registry with generic
        locators like get_by_role('button', 'OK').

        Args
        ----
        ac_step_text : str
            The AC step text this selector satisfies (used as description).
        strategy : str
            Playwright locator strategy used.
        name : str
            Element name/text/placeholder used in the locator.
        selector : str
            CSS selector string (only for css_selector strategy).
        role : str
            ARIA role (only for get_by_role strategy).
        context : str
            URL pattern or page context where this was found.

        Returns
        -------
        str
            The registry key, or empty string if skipped.
        """
        # Skip trivially generic locators that would pollute the registry
        _SKIP_NAMES = {
            "",
            "button",
            "submit",
            "ok",
            "cancel",
            "close",
            "save",
            "yes",
            "no",
            "next",
            "back",
            "done",
            "confirm",
        }
        if not name or name.lower() in _SKIP_NAMES:
            return ""
        if strategy not in ("css_selector", "get_by_role", "get_by_text", "get_by_label", "get_by_placeholder"):
            return ""

        description = ac_step_text[:80]
        return self.record_hitl_selector(
            description=description,
            selector=selector or name,
            strategy=strategy,
            context=context,
            role=role,
            name=name,
        )

    def _save(self) -> None:
        """
        Write self._selectors back to selector_registry.json.
        Caller must hold self._lock.
        """
        now_date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        data = {
            "version": "1.0",
            "last_updated": now_date,
            "source": "vQA auto-updated (HITL + verified selectors)",
            "notes": "Contains both static Playwright-extracted and HITL-confirmed selectors.",
            "selectors": self._selectors,
        }
        try:
            _REGISTRY_PATH.write_text(
                json.dumps(data, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
        except OSError as e:
            logger.error("Selector registry: failed to write %s: %s", _REGISTRY_PATH, e)


# Module-level singleton — imported by planner.py
selector_registry = SelectorRegistry()
