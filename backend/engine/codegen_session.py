def _slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:50]


def _format_test_file(raw_code: str, ticket_id: str, ticket_summary: str, recorded_at: str) -> str:
    """Prepend a header comment and rename the generic 'test' to include the ticket."""
    display_name = f"{ticket_id}: {ticket_summary}"
    raw_code = re.sub(
        r"test\('test',",
        f"test({json.dumps(display_name)},",
        raw_code,
        count=1,
    )
    header = f"""/**
 * {ticket_id}: {ticket_summary}
 *
 * Generated by vQA codegen on {recorded_at}
 * Recorded by a human demonstrating the correct flow.
 */

"""
    return header + raw_code


def _update_playwright_index(
    test_path: Path,
    ticket_id: str,
    ticket_summary: str,
    step_names: list[str] | None = None,
) -> None:
    index_path = _PROJECT_ROOT / "playwright" / "playwright_index.json"
    if not index_path.exists():
        return

    with open(index_path) as f:
        index: list[dict] = json.load(f)

    rel_path = test_path.relative_to(_PROJECT_ROOT / "playwright")
    test_id = test_path.stem

    if any(e.get("id") == test_id for e in index):
        return

    resolved_steps = step_names or ([ticket_summary] if ticket_summary else ["Recorded demo"])
    index.append({
        "id": test_id,
        "file": str(rel_path),
        "jira_keys": [ticket_id],
        "description": f"{ticket_id}: {ticket_summary}",
        "steps_count": len(resolved_steps),
        "step_names": resolved_steps,
    })

    with open(index_path, "w") as f:
        json.dump(index, f, indent=2)
    logger.info("[codegen] playwright_index.json updated with %s (%d steps)", test_id, len(resolved_steps))


def _record_run(ticket_id: str, duration_ms: int) -> str:
    from backend.storage.run_history import RunHistory as RunHistoryStore

    rh = RunHistoryStore()
    run_id = f"codegen-{uuid.uuid4().hex[:12]}"
    rh.record_run(
        run_id=run_id,
        ticket_id=ticket_id,
        role="codegen",
        status="passed",
        duration_ms=duration_ms,
        ac_total=1,
        ac_passed=1,
    )
    return run_id


async def _github_api_commit(
    test_path: Path,
    index_path: Path,
    ticket_id: str,
    ticket_summary: str,
) -> dict:
    """
    Commit the recorded test and updated index to GitHub via the REST API.
    No git binary required. Returns {commit_hash, branch, pr_url}.
    """
    token = settings.github_token
    if not token:
        raise RuntimeError(
            "GITHUB_TOKEN is not configured — cannot commit via GitHub API. "
            "Set the GITHUB_TOKEN environment variable."
        )

    repo = settings.github_repo
    if not repo or "/" not in repo:
        raise RuntimeError(
            f"GITHUB_REPO is not a valid 'owner/repo' value: {repo!r}. "
            "Set the GITHUB_REPO environment variable."
        )

    api_headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    base_url = f"https://api.github.com/repos/{repo}"

    async with httpx.AsyncClient(timeout=30, headers=api_headers) as client:
        # Resolve the repo's default branch and its HEAD commit SHA
        repo_resp = await client.get(base_url)
        repo_resp.raise_for_status()
        default_branch: str = repo_resp.json()["default_branch"]

        ref_resp = await client.get(f"{base_url}/git/ref/heads/{default_branch}")
        ref_resp.raise_for_status()
        base_sha: str = ref_resp.json()["object"]["sha"]

        # Create a new branch
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M")
        branch = f"codegen/{_slugify(ticket_id)}-{timestamp}"

        branch_resp = await client.post(f"{base_url}/git/refs", json={
            "ref": f"refs/heads/{branch}",
            "sha": base_sha,
        })
        branch_resp.raise_for_status()

        # Create blobs for both files
        def _blob_payload(path: Path) -> str:
            return base64.b64encode(path.read_bytes()).decode()

        test_blob_resp = await client.post(f"{base_url}/git/blobs", json={
            "content": _blob_payload(test_path),
            "encoding": "base64",
        })
        test_blob_resp.raise_for_status()
        test_blob_sha: str = test_blob_resp.json()["sha"]

        index_blob_resp = await client.post(f"{base_url}/git/blobs", json={
            "content": _blob_payload(index_path),
            "encoding": "base64",
        })
        index_blob_resp.raise_for_status()
        index_blob_sha: str = index_blob_resp.json()["sha"]

        # Resolve base tree SHA from the HEAD commit
        commit_resp = await client.get(f"{base_url}/git/commits/{base_sha}")
        commit_resp.raise_for_status()
        base_tree_sha: str = commit_resp.json()["tree"]["sha"]

        # Build a new tree on top of the base
        test_rel = str(test_path.relative_to(_PROJECT_ROOT))
        index_rel = str(index_path.relative_to(_PROJECT_ROOT))

        tree_resp = await client.post(f"{base_url}/git/trees", json={
            "base_tree": base_tree_sha,
            "tree": [
                {"path": test_rel, "mode": "100644", "type": "blob", "sha": test_blob_sha},
                {"path": index_rel, "mode": "100644", "type": "blob", "sha": index_blob_sha},
            ],
        })
        tree_resp.raise_for_status()
        tree_sha: str = tree_resp.json()["sha"]

        # Create the commit
        commit_msg = (
            f"test(codegen): add recorded Playwright test for {ticket_id}\n\n"
            f"{ticket_summary}"
        )
        new_commit_resp = await client.post(f"{base_url}/git/commits", json={
            "message": commit_msg,
            "tree": tree_sha,
            "parents": [base_sha],
        })
        new_commit_resp.raise_for_status()
        commit_sha: str = new_commit_resp.json()["sha"]
        commit_hash = commit_sha[:7]

        # Fast-forward the branch ref to the new commit
        update_ref_resp = await client.patch(f"{base_url}/git/refs/heads/{branch}", json={
            "sha": commit_sha,
        })
        update_ref_resp.raise_for_status()

        # Open a pull request
        pr_body = (
            f"## Recorded Playwright Test\n\n"
            f"**Ticket:** [{ticket_id}](https://vcreative.atlassian.net/browse/{ticket_id})\n"
            f"**Summary:** {ticket_summary}\n\n"
            f"This test was recorded by a human demonstrating the correct flow via vQA codegen "
            f"and automatically transformed to use project helpers (setup.ts fixture, NavHelper, "
            f"QO_helpers generators, OrderHelper date pickers).\n\n"
            f"### Review Checklist\n"
            f"- [ ] Search for `⚠️ FRAGILE` comments — each one needs a manual fix before this test is stable\n"
            f"- [ ] Hover-to-reveal action buttons have explicit `.hover()` calls added\n"
            f"- [ ] Any remaining hardcoded entity names/IDs are replaced with generated data\n"
            f"- [ ] Test leaves the environment in the same state it started (data cleanup performed)\n"
            f"- [ ] Run once locally against `TEST_ENV=qa` to confirm the transformation is correct\n"
        )
        pr_resp = await client.post(f"{base_url}/pulls", json={
            "title": f"test(codegen): {ticket_id} — recorded Playwright test",
            "body": pr_body,
            "head": branch,
            "base": default_branch,
        })
        pr_resp.raise_for_status()
        pr_url: str = pr_resp.json()["html_url"]

        logger.info("[codegen] PR opened: %s", pr_url)
        return {"commit_hash": commit_hash, "branch": branch, "pr_url": pr_url}


