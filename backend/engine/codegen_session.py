"""
vQA — Codegen Session Manager (Playwright-native codegen)
=========================================================
Module: backend/engine/codegen_session.py

Launches `playwright codegen --target=playwright-test --output=<file> <url>`
as a subprocess. The user interacts with the real Playwright browser; Playwright
writes TypeScript test code in real-time. When the user closes the browser the
process exits, and a background monitor task reads the output, wraps it with
ticket metadata, saves it to playwright/tests/, updates playwright_index.json,
records a passed run in run_history.db, and commits to GitHub via the REST API
(no git binary required).

Session lifecycle:
  POST /codegen/start        → launch subprocess + monitor task, return session_id
  WS   /ws/codegen/{sid}    → relays {"type": "saving"} then {"type": "recording_done"}
  POST /codegen/{sid}/cancel → kill subprocess, cleanup temp file
"""

import asyncio
import base64
import json
import logging
import os
import re
import signal
import sys
import tempfile
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal, Optional

import httpx
from fastapi import WebSocket

from backend.config import settings

logger = logging.getLogger(__name__)

_PROJECT_ROOT = Path(__file__).parent.parent.parent

_sessions: dict[str, "CodegenSessionState"] = {}
_ws_clients: dict[str, set[WebSocket]] = {}


@dataclass
class CodegenSessionState:
    session_id: str
    ticket_id: str
    ticket_summary: str
    target_url: str
    process: asyncio.subprocess.Process
    output_file: str
    started_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    status: Literal["recording", "saving", "confirm_pr", "done", "error", "cancelled"] = "recording"
    result: Optional[dict] = None
    pending_result: Optional[dict] = None  # local result before PR confirmation
    pr_confirm_event: asyncio.Event = field(default_factory=asyncio.Event)
    pr_decision: Optional[Literal["confirm", "skip"]] = None


# ---------------------------------------------------------------------------
# WebSocket broadcast
# ---------------------------------------------------------------------------


async def _broadcast(session_id: str, message: dict) -> None:
    clients = _ws_clients.get(session_id, set())
    dead = set()
    for ws in clients:
        try:
            await ws.send_json(message)
        except Exception:
            dead.add(ws)
    clients -= dead


