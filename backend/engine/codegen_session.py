async def start_session(
    session_id: str,
    ticket_id: str,
    ticket_summary: str,
    target_url: str,
) -> "CodegenSessionState":
    output_fd, output_file = tempfile.mkstemp(suffix=".ts", prefix=f"vqa-codegen-{session_id}-")
    os.close(output_fd)

    playwright_bin = Path(sys.executable).parent / "playwright"
    if not playwright_bin.exists():
        playwright_bin = "playwright"  # fall back to PATH

    process = await asyncio.create_subprocess_exec(
        str(playwright_bin),
        "codegen",
        "--target", "playwright-test",
        "--output", output_file,
        target_url,
        stdout=asyncio.subprocess.DEVNULL,
        stderr=asyncio.subprocess.PIPE,
    )

    state = CodegenSessionState(
        session_id=session_id,
        ticket_id=ticket_id,
        ticket_summary=ticket_summary,
        target_url=target_url,
        process=process,
        output_file=output_file,
    )
    _sessions[session_id] = state
    _ws_clients[session_id] = set()

    logger.info("[codegen:%s] playwright codegen launched (pid=%s) → %s", session_id, process.pid, output_file)
    return state


# ---------------------------------------------------------------------------
# Monitor task (runs in background after start_session)
# ---------------------------------------------------------------------------


async def monitor_session(session_id: str) -> None:
    """Wait for the playwright codegen process to exit, then save and commit."""
    state = _sessions.get(session_id)
    if not state:
        return

    try:
        await state.process.wait()
    except Exception as e:
        logger.error("[codegen:%s] process.wait() error: %s", session_id, e)

    state = _sessions.get(session_id)
    if not state or state.status == "cancelled":
        return

    state.status = "saving"
    await _broadcast(session_id, {"type": "saving"})

    try:
        output_file = state.output_file
        if not os.path.exists(output_file) or os.path.getsize(output_file) < 50:
            raise ValueError(
                "No actions were recorded — the Playwright browser was closed before any steps were performed."
            )

        with open(output_file) as f:
            raw_code = f.read()

        from backend.engine.codegen_transformer import transform_and_analyze
        transformed_code, transformations = await transform_and_analyze(raw_code, state.ticket_id)

        recorded_at = state.started_at.strftime("%Y-%m-%d %H:%M UTC")
        formatted = _format_test_file(transformed_code, state.ticket_id, state.ticket_summary, recorded_at)

        slug = _slugify(state.ticket_id)
        test_filename = f"{slug}-recorded.test.ts"
        test_path = _PROJECT_ROOT / "playwright" / "tests" / test_filename
        index_path = _PROJECT_ROOT / "playwright" / "playwright_index.json"

        with open(test_path, "w") as f:
            f.write(formatted)
        logger.info("[codegen:%s] Test file written: %s", session_id, test_path)

        step_names = transformations.get("step_names") if transformations else None
        _update_playwright_index(test_path, state.ticket_id, state.ticket_summary, step_names)

        duration_ms = int((datetime.now(timezone.utc) - state.started_at).total_seconds() * 1000)
        run_id = _record_run(state.ticket_id, duration_ms)

        # Pause and ask user to confirm before submitting the PR
        pending = {
            "test_file": test_filename,
            "test_path": f"playwright/tests/{test_filename}",
            "run_id": run_id,
            "lines": len(formatted.splitlines()),
            "_test_path_abs": str(test_path),
            "_index_path_abs": str(index_path),
        }
        if transformations is not None:
            pending["transformations"] = transformations
        state.pending_result = pending
        state.status = "confirm_pr"

        await _broadcast(session_id, {
            "type": "ready_for_pr",
            "test_file": test_filename,
            "test_path": f"playwright/tests/{test_filename}",
            "lines": pending["lines"],
        })
        logger.info("[codegen:%s] Awaiting PR confirmation from user", session_id)

        try:
            await asyncio.wait_for(state.pr_confirm_event.wait(), timeout=300.0)
        except asyncio.TimeoutError:
            logger.warning("[codegen:%s] PR confirmation timed out — skipping PR", session_id)
            state.pr_decision = "skip"

        if state.pr_decision == "confirm":
            git_info = await _github_api_commit(test_path, index_path, state.ticket_id, state.ticket_summary)
            result = {**{k: v for k, v in pending.items() if not k.startswith("_")},
                      "commit_hash": git_info["commit_hash"],
                      "branch": git_info["branch"],
                      "pr_url": git_info["pr_url"]}
            logger.info(
                "[codegen:%s] Done — %s committed as %s, PR: %s",
                session_id, test_filename, git_info["commit_hash"], git_info["pr_url"],
            )
        else:
            result = {k: v for k, v in pending.items() if not k.startswith("_")}
            logger.info("[codegen:%s] Done — %s saved locally (no PR)", session_id, test_filename)

        state.result = result
        state.status = "done"

        await _broadcast(session_id, {"type": "recording_done", **result})

    except Exception as e:
        logger.error("[codegen:%s] Save/commit failed: %s", session_id, e, exc_info=True)
        state.status = "error"
        await _broadcast(session_id, {"type": "error", "message": str(e)})

    finally:
        try:
            os.unlink(state.output_file)
        except Exception:
            pass


# ---------------------------------------------------------------------------
# PR confirmation / skip
# ---------------------------------------------------------------------------


async def confirm_pr(session_id: str) -> dict:
    """Signal that the user approved the PR. monitor_session will proceed with commit."""
    state = _sessions.get(session_id)
    if not state or state.status != "confirm_pr":
        return {"success": False, "error": "Session not awaiting PR confirmation"}
    state.pr_decision = "confirm"
    state.pr_confirm_event.set()
    return {"success": True}


async def skip_pr(session_id: str) -> dict:
    """Signal that the user skipped the PR. monitor_session will save without committing."""
    state = _sessions.get(session_id)
    if not state or state.status != "confirm_pr":
        return {"success": False, "error": "Session not awaiting PR confirmation"}
    state.pr_decision = "skip"
    state.pr_confirm_event.set()
    return {"success": True}


# ---------------------------------------------------------------------------
# Session cancel / TTL cleanup
# ---------------------------------------------------------------------------


async def finish_session(session_id: str) -> dict:
    """
    Signal the recorder to stop and save.

    In production the Playwright browser runs inside a headless Xvfb display
    streamed via noVNC, and there's no reliable window-close affordance for the
    user. This endpoint sends SIGTERM to the `playwright codegen` subprocess,
    which closes the browser cleanly, flushes the generated TS to `--output`,
    and exits — causing `monitor_session`'s `process.wait()` to return and
    proceed with the normal save + `ready_for_pr` flow.
    """
    state = _sessions.get(session_id)
    if not state:
        return {"success": False, "error": "Session not found"}
    if state.status != "recording":
        return {"success": False, "error": f"Session not recording (status={state.status})"}
    try:
        state.process.send_signal(signal.SIGTERM)
        logger.info("[codegen:%s] SIGTERM sent to playwright codegen (pid=%s)", session_id, state.process.pid)
    except ProcessLookupError:
        logger.info("[codegen:%s] Process already exited before SIGTERM", session_id)
    except Exception as e:
        logger.error("[codegen:%s] Failed to send SIGTERM: %s", session_id, e)
        return {"success": False, "error": str(e)}
    return {"success": True}


async def cancel_session(session_id: str) -> None:
    state = _sessions.pop(session_id, None)
    if state:
        state.status = "cancelled"
        try:
            state.process.kill()
            await state.process.wait()
        except Exception:
            pass
        try:
            os.unlink(state.output_file)
        except Exception:
            pass
    _ws_clients.pop(session_id, None)


async def _cleanup_expired_sessions() -> None:
    """Background task — culls sessions older than 30 minutes."""
    while True:
        await asyncio.sleep(300)
        now = datetime.now(timezone.utc)
        expired = [
            sid
            for sid, state in list(_sessions.items())
            if (now - state.started_at).total_seconds() > 1800
        ]
        for sid in expired:
            logger.info("[codegen:%s] TTL expired — cancelling session", sid)
            await cancel_session(sid)
