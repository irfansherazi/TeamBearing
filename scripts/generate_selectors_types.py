#!/usr/bin/env python3
"""
scripts/generate_selectors_types.py
=====================================
Week 1 build-time utility.

Reads a tenant's selectors.json and emits a TypeScript file containing:
  - A TenantSelectorKey union type (all valid key strings)
  - A SELECTORS constant (key → raw selector string)
  - A getLocator() helper (typed, returns Playwright Locator)

This ensures that if the LLM hallucinates a selector key, `tsc --noEmit`
catches it as a compile-time error in the Validate step (TS2345).

Usage:
    python3 scripts/generate_selectors_types.py --tenant vpromedia

Output:
    playwright/utils/generated/<tenant_id>_selectors.ts

The generated file is checked into the repo. Re-run whenever selectors.json changes.
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent


def load_selectors(tenant_id: str) -> dict:
    path = ROOT / "tenants" / tenant_id / "selectors.json"
    if not path.exists():
        print(f"ERROR: selectors.json not found at {path}", file=sys.stderr)
        sys.exit(1)
    with open(path) as f:
        data = json.load(f)
    # Filter out the _readme meta-key
    return {k: v for k, v in data.items() if not k.startswith("_")}


def generate_ts(tenant_id: str, selectors: dict) -> str:
    keys = list(selectors.keys())

    # Build the union type string
    union_lines = "\n  | ".join(f'"{k}"' for k in keys)
    union_type = f"  | {union_lines}"

    # Build the SELECTORS constant
    selector_entries = []
    for key, value in selectors.items():
        raw = value["selector"].replace("\\", "\\\\").replace("`", "\\`")
        desc = value.get("description", "").replace("\\", "\\\\").replace("`", "\\`")
        selector_entries.append(f'  // {desc}\n  "{key}": `{raw}`,')
    selector_body = "\n\n".join(selector_entries)

    display_name = tenant_id.replace("_", " ").title()

    return f'''/**
 * AUTO-GENERATED — DO NOT EDIT MANUALLY
 * =========================================
 * Source: tenants/{tenant_id}/selectors.json
 * Generated by: scripts/generate_selectors_types.py --tenant {tenant_id}
 *
 * Re-run the generator whenever selectors.json changes.
 * Commit this file; it provides compile-time safety for getLocator() calls.
 *
 * Tenant: {display_name}
 * Keys: {len(keys)}
 */

import {{ type Locator, type Page }} from \'@playwright/test\';

// ---------------------------------------------------------------------------
// Typed key union — compile-time safety for getLocator() calls
// If the LLM hallucinates a key, tsc --noEmit catches it as TS2345.
// ---------------------------------------------------------------------------

export type TenantSelectorKey =
{union_type};

// ---------------------------------------------------------------------------
// Raw selector map (key → CSS / Playwright selector string)
// ---------------------------------------------------------------------------

export const SELECTORS: Record<TenantSelectorKey, string> = {{
{selector_body}
}};

// ---------------------------------------------------------------------------
// getLocator — typed helper used in generated .spec.ts files
// ---------------------------------------------------------------------------

/**
 * Return a Playwright Locator for the given vQA selector key.
 *
 * @param page  - The Playwright Page instance
 * @param key   - A TenantSelectorKey from selectors.json (compile-time checked)
 * @param opts  - Optional Playwright locator options (e.g. {{ hasText: "Submit" }})
 *
 * Usage in generated tests:
 *   const btn = getLocator(page, "search-execute-btn");
 *   await btn.click();
 */
export function getLocator(
  page: Page,
  key: TenantSelectorKey,
  opts?: Parameters<Page["locator"]>[1],
): Locator {{
  return page.locator(SELECTORS[key], opts);
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate TypeScript selector types from selectors.json")
    parser.add_argument("--tenant", required=True, help="Tenant ID (e.g. vpromedia)")
    parser.add_argument("--dry-run", action="store_true", help="Print output without writing to disk")
    args = parser.parse_args()

    tenant_id = args.tenant
    selectors = load_selectors(tenant_id)

    ts_content = generate_ts(tenant_id, selectors)

    if args.dry_run:
        print(ts_content)
        return

    out_dir = ROOT / "playwright" / "utils" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)

    out_path = out_dir / f"{tenant_id}_selectors.ts"
    out_path.write_text(ts_content, encoding="utf-8")

    print(f"✅ Generated: {out_path.relative_to(ROOT)}")
    print(f"   Keys: {len(selectors)}")
    print(f"   Tenant: {tenant_id}")


if __name__ == "__main__":
    main()
