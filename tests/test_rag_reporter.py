class TestRagStatsTelemetry:
    """
    Tests that planner_node populates rag_selector_stats with telemetry
    on each SelectorRAG.query() call.
    """

    def test_rag_stats_dict_has_required_fields(self):
        """
        Each rag_selector_stats entry must contain:
          step_id, entries_retrieved, chars_injected, retrieval_latency_ms
        """
        # This validates the schema expected by the reporter renderer.
        required_keys = {"step_id", "entries_retrieved", "chars_injected", "retrieval_latency_ms"}
        example_entry = {
            "step_id": "step-3",
            "entries_retrieved": 12,
            "chars_injected": 870,
            "retrieval_latency_ms": 2.3,
        }
        missing = required_keys - set(example_entry.keys())
        assert not missing, f"rag_selector_stats entry missing keys: {missing}"

    def test_rag_stats_entries_retrieved_is_non_negative_int(self):
        """entries_retrieved must be a non-negative integer."""
        entry = {
            "step_id": "s-0",
            "entries_retrieved": 5,
            "chars_injected": 400,
            "retrieval_latency_ms": 1.5,
        }
        assert isinstance(entry["entries_retrieved"], int)
        assert entry["entries_retrieved"] >= 0

    def test_rag_stats_chars_injected_within_budget(self):
        """chars_injected must be ≤ 2000 (budget cap enforced by SelectorRAG)."""
        entry = {
            "step_id": "s-0",
            "entries_retrieved": 10,
            "chars_injected": 1850,
            "retrieval_latency_ms": 1.2,
        }
        assert entry["chars_injected"] <= 2000, "chars_injected must respect the 2000-char budget cap"

    def test_rag_stats_latency_is_positive_float(self):
        """retrieval_latency_ms must be a positive number."""
        entry = {
            "step_id": "s-0",
            "entries_retrieved": 5,
            "chars_injected": 400,
            "retrieval_latency_ms": 0.7,
        }
        assert isinstance(entry["retrieval_latency_ms"], float | int)
        assert entry["retrieval_latency_ms"] >= 0


