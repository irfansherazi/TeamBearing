class TestRagQueryTelemetry:
    """
    Tests that SelectorRAG.query() behaves correctly and that callers can
    measure the latency externally (since stats are populated by planner_node).
    """

    def test_query_result_is_within_budget(self, tmp_path):
        """
        SelectorRAG.query() result must be ≤ 2000 chars (budget cap enforced).
        """
        from backend.kb.selector_rag import SelectorRAG

        registry = tmp_path / "reg.json"
        # Build a registry with many entries to trigger trimming
        entries = {}
        for i in range(50):
            entries[f"btn-{i}"] = {
                "description": f"Button number {i} for action {i}",
                "context": f"Used in context {i} for various operations on the dashboard page",
                "strategies": [
                    {"method": "get_by_role", "role": "button", "name": f"Button {i}", "selector": f".btn-{i}"},
                ],
            }
        import json

        registry.write_text(json.dumps({"selectors": entries}))

        bp_dir = tmp_path / "blueprints"
        bp_dir.mkdir()
        idx_dir = tmp_path / "selector_rag"

        rag = SelectorRAG(
            registry_path=registry,
            blueprints_dir=bp_dir,
            index_dir=idx_dir,
        )
        rag.build_index()

        result = rag.query("Click the button to submit the form")
        assert len(result) <= 2000, f"query() result must be ≤ 2000 chars, got {len(result)}"

    def test_query_returns_string(self, tmp_path):
        """query() must always return a string (even empty)."""
        from backend.kb.selector_rag import SelectorRAG

        rag = SelectorRAG(
            registry_path=tmp_path / "nonexistent.json",
            blueprints_dir=tmp_path / "bp",
            index_dir=tmp_path / "idx",
        )
        result = rag.query("Anything")
        assert isinstance(result, str)
