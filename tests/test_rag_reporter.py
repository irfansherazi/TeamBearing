class TestAutoRebuildOnPlannerLoad:
    """
    Tests that the planner module-level auto-rebuild check works correctly.
    This is implemented as a function _check_and_rebuild_selector_rag_if_stale()
    that is called at module import time (or first planner call).
    """

    def test_auto_rebuild_function_exists_in_selector_rag(self):
        """SelectorRAG must have a rebuild_if_stale() method for planner to call."""
        from backend.kb.selector_rag import SelectorRAG

        rag = SelectorRAG.__new__(SelectorRAG)
        assert hasattr(rag, "rebuild_if_stale"), "SelectorRAG must expose rebuild_if_stale() for planner auto-rebuild"

    def test_rebuild_in_background_method_exists(self):
        """SelectorRAG must have rebuild_in_background() for non-blocking rebuild."""
        from backend.kb.selector_rag import SelectorRAG

        rag = SelectorRAG.__new__(SelectorRAG)
        assert hasattr(rag, "rebuild_in_background"), (
            "SelectorRAG must expose rebuild_in_background() for async rebuild"
        )

    def test_selector_rag_singleton_is_importable(self):
        """The module-level selector_rag singleton must be importable."""
        from backend.kb.selector_rag import selector_rag

        assert selector_rag is not None, "selector_rag singleton must be importable"

    def test_rebuild_in_background_does_not_block(self, tmp_path):
        """rebuild_in_background() must return immediately (non-blocking)."""
        import time as _time

        registry = tmp_path / "reg.json"
        registry.write_text('{"selectors": {"x": {"description": "X", "context": "", "strategies": []}}}')
        bp_dir = tmp_path / "bp"
        bp_dir.mkdir()
        idx_dir = tmp_path / "idx"

        rag = SelectorRAG(
            registry_path=registry,
            blueprints_dir=bp_dir,
            index_dir=idx_dir,
        )
        # Must return almost immediately (< 500ms)
        t_start = _time.monotonic()
        rag.rebuild_in_background()
        elapsed_ms = (_time.monotonic() - t_start) * 1000
        assert elapsed_ms < 500, f"rebuild_in_background() must be non-blocking, took {elapsed_ms:.1f}ms"

    def test_rag_stats_reducer_in_state(self):
        """
        VQAState.rag_selector_stats must use operator.add reducer so stats
        accumulate across all planner calls without overwriting.
        """
        import operator
        from typing import get_args, get_type_hints

        from backend.engine.state import VQAState

        hints = get_type_hints(VQAState, include_extras=True)
        field = hints.get("rag_selector_stats")
        assert field is not None, "VQAState must have rag_selector_stats field"

        # Should be Annotated[list[dict], operator.add]
        args = get_args(field)
        assert len(args) >= 2, "rag_selector_stats must be Annotated with a reducer"
        reducer = args[1]
        assert reducer is operator.add, "rag_selector_stats reducer must be operator.add (append semantics)"


