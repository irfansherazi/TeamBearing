"""
tests/test_playwright_registry.py
===================================
Tests for PlaywrightRegistry — updated to match canonical implementation.

The original tests expected filesystem-scan behavior (discover .spec.ts files
and persist them). The new implementation (AC-BACK-1) reads from a pre-generated
JSON index file (playwright/playwright_index.json) and does NOT write to it.

These tests have been updated to reflect the canonical behavior while preserving
the same test intent.
"""

import json

import pytest

# We expect this import to fail initially (RED phase)
try:
    from backend.storage.playwright_registry import PlaywrightRegistry
except ImportError:
    PlaywrightRegistry = None


SAMPLE_ENTRY = {
    "id": "demo.test",
    "file": "tests/demo.test.ts",
    "jira_keys": [],
    "description": "Demo test",
    "steps_count": 1,
    "step_names": ["Step 1"],
}


@pytest.fixture
def temp_registry_dir(tmp_path):
    """Create a temporary directory for tests and a registry file."""
    tests_dir = tmp_path / "playwright_tests"
    tests_dir.mkdir()
    registry_file = tmp_path / "playwright_registry.json"
    registry_file.write_text("[]")
    return tests_dir, registry_file


@pytest.fixture
def registry(temp_registry_dir):
    if PlaywrightRegistry is None:
        pytest.fail("PlaywrightRegistry not implemented yet")
    tests_dir, registry_file = temp_registry_dir
    return PlaywrightRegistry(
        tests_dir=str(tests_dir),
        registry_file=str(registry_file)
    )


def test_registry_initialization(registry):
    """Verify that the registry initializes correctly (empty index → empty list)."""
    assert registry.list_tests() == []


def test_registry_discover_tests(tmp_path):
    """
    Verify that after the index is populated, registry.list_tests() returns entries.

    NOTE: The canonical registry reads from a pre-generated JSON index file,
    not from filesystem discovery. This test writes entries to the index file
    and verifies the registry returns them.
    """
    if PlaywrightRegistry is None:
        pytest.fail("PlaywrightRegistry not implemented yet")

    tests_dir = tmp_path / "playwright_tests"
    tests_dir.mkdir()
    index_file = tmp_path / "playwright_index.json"
    # Write a single entry to the index (as the sync script would do)
    index_file.write_text(json.dumps([SAMPLE_ENTRY]))

    reg = PlaywrightRegistry(
        tests_dir=str(tests_dir),
        registry_file=str(index_file),
    )
    reg.refresh()
    tests = reg.list_tests()
    assert len(tests) == 1
    assert tests[0]["id"] == "demo.test"


