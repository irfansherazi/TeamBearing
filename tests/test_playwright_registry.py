def test_registry_persistence(tmp_path):
    """
    Verify that the index file is READ correctly (not overwritten) by registry.

    The canonical index file is pre-generated by scripts/sync_playwright_index.py.
    The registry does NOT write to it — it reads from it on refresh().
    """
    if PlaywrightRegistry is None:
        pytest.fail("PlaywrightRegistry not implemented yet")

    tests_dir = tmp_path / "playwright_tests"
    tests_dir.mkdir()
    index_file = tmp_path / "playwright_index.json"
    index_file.write_text(json.dumps([SAMPLE_ENTRY]))

    reg = PlaywrightRegistry(
        tests_dir=str(tests_dir),
        registry_file=str(index_file),
    )
    reg.refresh()

    # Verify the index file content is intact (not overwritten by registry)
    with open(index_file, "r") as f:
        data = json.load(f)
    # File should still contain the original entry we wrote
    assert len(data) == 1
    assert data[0]["id"] == "demo.test"


